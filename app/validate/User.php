declare (strict_types = 1);

namespace app\validate;

use think\Validate;

class User extends Validate
{
    /**
     * 定义验证规则
     * 格式：'字段名'	=>	['规则1','规则2'...]
     *
     * @var array
     */	
	protected $rule = [
        'email|邮箱'      =>      'require|/^\w+([-+.]\w+)*@\w+([-.]\w+)*\.\w+([-.]\w+)*$/',
        'capacity|配额'      =>      'require',
    ];

    /**
     * 验证场景
     * edit：编辑成员时 email 只做必填校验，不强制邮箱格式。
     * 原因：安装器把根管理员 email 写成 "admin"（非邮箱格式），
     * 编辑该账号时若套用严格邮箱正则会误报「邮箱规则错误」。
     */
    protected $scene = [
        'edit' => ['email' => 'require', 'capacity'],
    ];

}
